export const messages: Record<Lang, Record<string, string>> = { zh, en };

export type MsgKey = keyof typeof zh & string;

export function translate(lang: Lang, key: MsgKey, params?: Record<string, string | number>): string {
  let s = messages[lang][key] ?? messages.zh[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split('{' + k + '}').join(String(v));
    }
  }
  return s;
}

// i18n React context. App provides the current lang; components call useT().
export const LangContext = createContext<Lang>('zh');

export function useLang(): Lang {
  return useContext(LangContext);
}

export function useT() {
  const lang = useContext(LangContext);
  return (key: MsgKey, params?: Record<string, string | number>) => translate(lang, key, params);
}

export function isLang(v: unknown): v is Lang {
  return v === 'zh' || v === 'en';
}
